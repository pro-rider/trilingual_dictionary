"""Generate docs/IMAGE_AUDIT.md from the images table (Phase 9).

Every shipped thumbnail must have a traceable source and licence. Anything that
does not is listed as a problem rather than quietly dropped from the report.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DB = REPO / "backend" / "data" / "build" / "dictionary.sqlite"
OUT = REPO / "docs" / "IMAGE_AUDIT.md"

con = sqlite3.connect(DB)
con.row_factory = sqlite3.Row
cols = [r[1] for r in con.execute("PRAGMA table_info(images)")]
rows = con.execute("SELECT * FROM images ORDER BY image_id").fetchall()
print("columns:", cols)

LICENCE_FIELD = next((c for c in ("license", "licence", "license_name") if c in cols), None)
SOURCE_FIELD = next((c for c in ("source", "provider", "source_name") if c in cols), None)
ASSET_FIELD = next((c for c in ("thumb_asset", "asset_path") if c in cols), None)
URL_FIELD = next((c for c in ("remote_url", "original_url", "detail_url") if c in cols), None)
STATUS_FIELD = next((c for c in ("verification_status", "asset_status") if c in cols), None)
print("fields:", LICENCE_FIELD, SOURCE_FIELD, ASSET_FIELD, URL_FIELD, STATUS_FIELD)

missing_file = []
no_licence = []
per_licence: dict[str, int] = {}
per_source: dict[str, int] = {}
for row in rows:
    licence = (row[LICENCE_FIELD] or "").strip() if LICENCE_FIELD else ""
    source = (row[SOURCE_FIELD] or "").strip() if SOURCE_FIELD else ""
    per_licence[licence or "(none)"] = per_licence.get(licence or "(none)", 0) + 1
    per_source[source or "(none)"] = per_source.get(source or "(none)", 0) + 1
    if not licence:
        no_licence.append(row["image_id"])
    asset = (row[ASSET_FIELD] or "") if ASSET_FIELD else ""
    if not asset:
        missing_file.append((row["image_id"], "(no thumbnail asset recorded)"))
    elif not (REPO / asset).exists():
        missing_file.append((row["image_id"], asset))

lines = [
    "# Image licence audit",
    "",
    "DRAFT — generated by backend/tools/audit_images.py; needs human/legal review",
    "before a store submission.  This file is the answer to \"prove every shipped",
    "thumbnail is licensed\".",
    "",
    f"Images in the database: **{len(rows)}**.",
    "",
    "## Counts by licence",
    "",
    "| licence | images |",
    "|---|---|",
]
for licence, count in sorted(per_licence.items(), key=lambda kv: -kv[1]):
    lines.append(f"| {licence} | {count} |")
lines += ["", "## Counts by source", "", "| source | images |", "|---|---|"]
for source, count in sorted(per_source.items(), key=lambda kv: -kv[1]):
    lines.append(f"| {source} | {count} |")

lines += ["", "## Problems", ""]
if no_licence:
    lines.append(f"- {len(no_licence)} image(s) with no licence recorded: "
                 + ", ".join(str(i) for i in no_licence[:20]))
else:
    lines.append("- No image is missing a licence field.")
if missing_file:
    lines.append(f"- {len(missing_file)} thumbnail file(s) referenced but absent from "
                 "the repository:")
    for image_id, asset in missing_file[:20]:
        lines.append(f"  - image {image_id}: `{asset}`")
else:
    lines.append("- Every referenced thumbnail file exists on disk.")

lines += ["", "## Per-image detail", "",
          "| id | title | licence | author | attribution (as shipped) | "
          "status | thumbnail | original |",
          "|---|---|---|---|---|---|---|---|"]
for row in rows:
    def val(name: str) -> str:
        return (row[name] or "") if name in cols else ""

    lines.append(
        f"| {row['image_id']} | {val('title')} | {val('license')} | {val('author')} | "
        f"{val('attribution_text')} | {val('verification_status')} | "
        f"{val('thumb_asset')} | {val('detail_url')} |"
    )

lines += ["", "## Required attribution",
          "",
          "The app shows the author, licence and source URL on the entry detail",
          "screen for every image. CC BY-SA images additionally require the",
          "share-alike notice, which lib/features/about/credits_screen.dart carries.",
          "Every original URL above is a Wikimedia page; `license_url` in the",
          "database is the deed the build recorded at download time."]

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT, "rows", len(rows), "missing files", len(missing_file),
      "no licence", len(no_licence))
