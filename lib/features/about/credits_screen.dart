import 'package:flutter/material.dart';

/// In-app licence and data-quality disclosure.
///
/// Play Store policy requires the attribution text for every CC BY-SA source to
/// be reachable from inside the app, not only from a web page. The strings here
/// mirror `CREDITS.md` at the repository root; if one changes, change both.
class CreditsScreen extends StatelessWidget {
  const CreditsScreen({super.key});

  static const List<(String, String, String)> _sources = [
    (
      'CC-CEDICT',
      'English glosses and the headword list (123,672 entries).',
      'CC BY-SA 4.0 — https://creativecommons.org/licenses/by-sa/4.0/',
    ),
    (
      'Chinese Wiktionary (zh.wiktionary)',
      'Chinese definitions imported after review, recorded row by row in the '
          'database provenance table.',
      'CC BY-SA 4.0 — https://creativecommons.org/licenses/by-sa/4.0/',
    ),
    (
      'Wikimedia Commons',
      'Entry images and their thumbnails, each with its own licence noted in '
          'the entry detail screen.',
      'Per-image licence shown on the image; usually CC BY-SA or public domain',
    ),
  ];

  static const String _shareAlikeNote =
      'CC BY-SA 4.0 material is shared under the same licence. Modifications: '
      'headwords were deduplicated, definitions were imported and normalised, '
      'and machine translations were added and marked as such.';

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Credits & licences')),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          const Text(
            'This dictionary is built from openly licensed data. Every source is '
            'listed below with its licence.',
            style: TextStyle(fontSize: 14),
          ),
          const SizedBox(height: 16),
          for (final (name, what, licence) in _sources) ...[
            Text(name, style: Theme.of(context).textTheme.titleMedium),
            const SizedBox(height: 4),
            Text(what),
            const SizedBox(height: 2),
            Text(licence, style: const TextStyle(fontSize: 12)),
            const Divider(height: 24),
          ],
          Text('Share-alike', style: Theme.of(context).textTheme.titleMedium),
          const SizedBox(height: 4),
          const Text(_shareAlikeNote),
          const SizedBox(height: 16),
          Text('Not included',
              style: Theme.of(context).textTheme.titleMedium),
          const SizedBox(height: 4),
          const Text(
            'Commercial dictionaries whose licence does not permit '
            'redistribution (for example the Xinhua dictionary and MoEDict) were '
            'never used to build the shipped database. They are kept out of the '
            'release by an automated licence check that fails the build.',
          ),
        ],
      ),
    );
  }
}

/// Explains the "reviewed" / "pending" labels the app shows on a sense.
///
/// The labels are not decoration: they say who produced the text. Hiding that
/// distinction would make machine output look human-checked.
class DataQualityScreen extends StatelessWidget {
  const DataQualityScreen({super.key});

  static const List<(String, String)> _labels = [
    (
      'Reviewed',
      'A person read this text and approved or corrected it. Nepali text marked '
          'reviewed has been through a native-speaker pass.',
    ),
    (
      'Machine translation (pending review)',
      'Generated by a language model and not yet checked by a person. Useful, '
          'but it can be wrong, especially for idioms and measure words.',
    ),
    (
      'Empty',
      'No text exists yet for this field. The app leaves it blank rather than '
          'repeating the headword or inventing a definition.',
    ),
  ];

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('About data quality')),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          const Text(
            'Chinese definitions and Nepali translations are not complete. '
            'Rather than fill the gaps with guesses, the app labels what it '
            'shows.',
          ),
          const SizedBox(height: 16),
          for (final (label, meaning) in _labels) ...[
            Text(label, style: Theme.of(context).textTheme.titleMedium),
            const SizedBox(height: 4),
            Text(meaning),
            const Divider(height: 24),
          ],
          const Text(
            'If you find an error, the review files in the project repository '
            'are the place to report it: every label traces back to a row that a '
            'reviewer can correct.',
          ),
        ],
      ),
    );
  }
}
