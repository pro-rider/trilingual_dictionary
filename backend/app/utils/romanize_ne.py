"""Deterministic Devanagari → Romanised Nepali (v2 spec).

Skipped in v1 UI, but kept server-side for a future feature. Generated by a
fixed mapping table so the same input always gives the same output (never AI),
and unit-testable. Handles the inherent 'a' (schwa): a consonant followed by a
vowel sign or a virāma loses its inherent 'a'; the word-final inherent 'a' is
dropped by convention (प्रकाश → prakāś).
"""

_SENTINEL = "\x00"  # internal marker for an inherent 'a'

_CONSONANTS = set("कखगघङचछजझञटठडढणतथदधनपफबभमयरलवशषसह")
_VOWEL_SIGNS = set("ा ि ी ु ू े ै ो ौ".split())
_VIRAMA = "्"

_BASE_MAP = {
    "अ": "a", "आ": "ā", "इ": "i", "ई": "ī", "उ": "u", "ऊ": "ū",
    "ए": "e", "ऐ": "ai", "ओ": "o", "औ": "au",
    "क": "k", "ख": "kh", "ग": "g", "घ": "gh", "ङ": "ṅ",
    "च": "c", "छ": "ch", "ज": "j", "झ": "jh", "ञ": "ñ",
    "ट": "ṭ", "ठ": "ṭh", "ड": "ḍ", "ढ": "ḍh", "ण": "ṇ",
    "त": "t", "थ": "th", "द": "d", "ध": "dh", "न": "n",
    "प": "p", "फ": "ph", "ब": "b", "भ": "bh", "म": "m",
    "य": "y", "र": "r", "ल": "l", "व": "v", "श": "ś",
    "ष": "ṣ", "स": "s", "ह": "h",
    "ा": "ā", "ि": "i", "ी": "ī", "ु": "u", "ू": "ū",
    "े": "e", "ै": "ai", "ो": "o", "ौ": "au",
    "ं": "ṁ", "ः": "ḥ", "ृ": "ṛ", "ऋ": "ṛ",
    "०": "0", "१": "1", "२": "2", "३": "3", "४": "4",
    "५": "5", "६": "6", "७": "7", "८": "8", "९": "9",
}


def romanize_ne(text: str) -> str:
    """Convert Devanagari to a simple learner-friendly romanisation."""
    chars = list(text)
    out: list[str] = []

    for i, ch in enumerate(chars):
        if ch == _VIRAMA:
            # Drop the inherent 'a' of the preceding consonant.
            if len(out) >= 2 and out[-1] == "a" and out[-2] == _SENTINEL:
                out.pop()
                out.pop()
            continue

        if ch in _VOWEL_SIGNS:
            out.append(_BASE_MAP[ch])
            continue

        if ch in _CONSONANTS:
            out.append(_BASE_MAP[ch])
            nxt = chars[i + 1] if i + 1 < len(chars) else None
            if nxt != _VIRAMA and nxt not in _VOWEL_SIGNS:
                out.append("a")
                out.append(_SENTINEL)
            continue

        out.append(_BASE_MAP.get(ch, ch))

    # Drop the word-final inherent 'a' by convention.
    while out and out[-1] == _SENTINEL:
        out.pop()
        if out and out[-1] == "a":
            out.pop()

    return "".join(c for c in out if c != _SENTINEL)
