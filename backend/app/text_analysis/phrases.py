# Precomputed lookup helpers ------------------------------------------------
_CJK_WORDS_BY_SURFACE: dict[str, dict] = {w["surface"]: w for w in CHINESE_WORDS}
_IDIOMS_BY_EN_KEY: dict[str, dict] = {i["key"]: i for i in IDIOMS if " " in i["key"]}
_IDIOMS_BY_CJK: dict[str, dict] = {i["surface"]: i for i in IDIOMS if not any(c.isascii() for c in i["surface"])}

# Chinese surfaces sorted longest-first for greedy segmentation.
CJK_WORD_SURFACES: list[str] = sorted(
    set(_CJK_WORDS_BY_SURFACE) | set(_IDIOMS_BY_CJK),
    key=len,
    reverse=True,
)


def chinese_word(surface: str) -> dict | None:
    """Return the curated Chinese word/compound for an exact surface."""
    return _CJK_WORDS_BY_SURFACE.get(surface)


def english_idiom_tokens(tokens: list[str], start: int) -> tuple[dict | None, int]:
    """Longest match of an English idiom starting at ``tokens[start]``.

    Returns ``(idiom, consumed)`` where ``consumed`` is the number of tokens the
    idiom spans (>= 2), or ``(None, 0)`` when no idiom begins here.
    """
    joined = " ".join(t.lower() for t in tokens[start:])
    # Try longest first (up to a reasonable window).
    for span in range(min(6, len(tokens) - start), 1, -1):
        phrase = " ".join(t.lower() for t in tokens[start:start + span])
        if phrase in _IDIOMS_BY_EN_KEY:
            return _IDIOMS_BY_EN_KEY[phrase], span
    return None, 0


def cjk_idiom(surface: str) -> dict | None:
    """Return a curated idiom for an exact Chinese surface (成语 / phrase)."""
    return _IDIOMS_BY_CJK.get(surface)
